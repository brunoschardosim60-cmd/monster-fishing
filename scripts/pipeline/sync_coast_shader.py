#!/usr/bin/env python3
"""Regenerate assets/shaders/archipelago_coast.gdshaderinc from scripts/world/archipelago_layout.gd.

The coastline is a contract shared by GDScript (collision, navigation, terrain, map) and the
ocean shaders (foam, depth, shelter). Edit LOBES / REMOTE_HARMONICS / COLD_CENTER in the .gd
file, then run:  python scripts/pipeline/sync_coast_shader.py
tests/island_layout_contract.gd fails if the two drift apart.
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "scripts/world/archipelago_layout.gd").read_text(encoding="utf-8")

def num(v):
    f = float(v)
    return str(int(f)) if f == int(f) else repr(f)

lobes_block = src[src.index("const LOBES"):src.index("## One record per lobe")]
lobes = re.findall(r"Vector4\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)", lobes_block)
harm_block = src[src.index("const REMOTE_HARMONICS"):]
harm_block = harm_block[:harm_block.index("\n")]
harmonics = re.findall(r"Vector2\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)", harm_block)
cold = re.search(r"const COLD_CENTER: Vector2=Vector2\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)", src).groups()
far = re.search(r"const FAR_CULL: float = ([\d.]+)", src).group(1)

n = len(lobes)
islands = ",".join("vec4(%s)" % ",".join(num(c) for c in l) for l in lobes)
terms = "\n".join(
    "\te+=%s*sin(%s*a+float((i*7+%d)%%17)*.37);" % (num(amp).lstrip("0") if float(amp) < 1 else num(amp), num(freq) + ".", int(float(freq)) * 13)
    for freq, amp in harmonics)

out = f"""// GENERATED by scripts/pipeline/sync_coast_shader.py from scripts/world/archipelago_layout.gd.
// Do not edit by hand: change the layout file and regenerate.
const int ISLAND_COUNT={n};
const vec4 ISLANDS[{n}]=vec4[{n}]({islands});
const vec2 COLD_CENTER=vec2({num(cold[0])},{num(cold[1])});
float edge_factor(int i,float a){{
	if(i<4||i==7){{return 1.+sin(a*3.+float(i)*1.7)*.055+cos(a*7.)*.025;}}
	float e=1.;
{terms}
	return e;
}}
vec4 coast_data(vec2 p) {{
	float nearest=10000.;float second=10000.;vec2 normal=vec2(0,-1);
	for(int i=0;i<ISLAND_COUNT;i++){{
		vec4 l=ISLANDS[i];vec2 q=(p-l.xy)/l.zw;
		float m=min(l.z,l.w);bool aurora=(i<4||i==7);
		float dist;
		if(dot(q,q)>{float(far)**2:.2f}){{dist=(length(q)-1.)*m;}}
		else{{dist=(length(q)-edge_factor(i,atan(q.y,q.x)))*m;}}
		if(dist<nearest){{if(!aurora){{second=nearest;}}nearest=dist;normal=normalize(q/l.zw+vec2(.000001));}}
		else if(!aurora&&dist<second){{second=dist;}}
	}}
	return vec4(nearest,normal,second);
}}
"""
(root / "assets/shaders/archipelago_coast.gdshaderinc").write_text(out, encoding="utf-8", newline="\n")
print(f"wrote archipelago_coast.gdshaderinc with {n} lobes, {len(harmonics)} harmonics")
